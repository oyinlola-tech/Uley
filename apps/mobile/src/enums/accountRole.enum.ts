export enum AccountRole {
  STUDENT = 'STUDENT',
  LANDLORD = 'LANDLORD',
  BUSINESS_ADVERTISER = 'BUSINESS_ADVERTISER',
  CARETAKER = 'CARETAKER',
  SCHOOL_ADMIN = 'SCHOOL_ADMIN',
  SUPER_ADMIN = 'SUPER_ADMIN',
  VERIFICATION_ADMIN = 'VERIFICATION_ADMIN',
  SAFETY_ADMIN = 'SAFETY_ADMIN',
  INSPECTION_ADMIN = 'INSPECTION_ADMIN',
  ACCOUNT_ADMIN = 'ACCOUNT_ADMIN',
}

export function isAdministratorAccountRole(role: AccountRole): boolean {
  return [AccountRole.SCHOOL_ADMIN, AccountRole.SUPER_ADMIN, AccountRole.VERIFICATION_ADMIN, AccountRole.SAFETY_ADMIN, AccountRole.INSPECTION_ADMIN, AccountRole.ACCOUNT_ADMIN].includes(role);
}
